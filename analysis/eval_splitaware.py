def delta_analysis(imp_means, val_cell_means, val_nuc_means, common_cts, gene_names):
    """Compare predicted delta to empirical validation delta.

    empirical_validation_delta[k, g] = val_cell_mean[k, g] - val_nuc_mean[k, g]
    predicted_validation_delta[k, g] = imp_mean[k, g] - val_nuc_mean[k, g]
    """
    results = {}
    all_gt, all_pred = [], []
    per_ct_corr = {}
    per_ct_r2 = {}

    for ct in common_cts:
        if ct not in imp_means or ct not in val_cell_means or ct not in val_nuc_means:
            continue
        delta_emp = val_cell_means[ct] - val_nuc_means[ct]
        delta_pred = imp_means[ct] - val_nuc_means[ct]

        r = _pearsonr_safe(delta_emp, delta_pred)
        per_ct_corr[ct] = r

        ss_res = np.sum((delta_pred - delta_emp) ** 2)
        ss_tot = np.sum((delta_emp - delta_emp.mean()) ** 2)
        per_ct_r2[ct] = float(1 - ss_res / ss_tot) if ss_tot > 0 else np.nan

        all_gt.append(delta_emp)
        all_pred.append(delta_pred)

    if not all_gt:
        return {"error": "no common cell types"}

    all_gt = np.concatenate(all_gt)
    all_pred = np.concatenate(all_pred)

    # Direction classification
    emp_sign = np.sign(all_gt)
    pred_sign = np.sign(all_pred)
    # Positive class: empirical delta > 0 (gene is cell-enriched)
    emp_pos = (emp_sign > 0)
    pred_pos = (pred_sign > 0)
    emp_neg = (emp_sign < 0)

    tp = int((emp_pos & pred_pos).sum())
    fp = int((~emp_pos & pred_pos).sum())
    fn = int((emp_pos & ~pred_pos).sum())
    tn = int((~emp_pos & ~pred_pos).sum())
    n_total = len(all_gt)
    n_zero = int((emp_sign == 0).sum())

    sign_acc = float((emp_sign == pred_sign).mean()) if n_total > 0 else np.nan
    sensitivity = tp / (tp + fn) if (tp + fn) > 0 else np.nan  # recall for positive shifts
    specificity = tn / (tn + fp) if (tn + fp) > 0 else np.nan  # recall for negative shifts
    balanced_acc = (sensitivity + specificity) / 2 if not np.isnan(sensitivity) and not np.isnan(specificity) else np.nan
    precision = tp / (tp + fp) if (tp + fp) > 0 else np.nan

    # MCC
    denom = np.sqrt(float((tp + fp) * (tp + fn) * (tn + fp) * (tn + fn)))
    mcc = float(tp * tn - fp * fn) / denom if denom > 0 else np.nan

    # AUROC using continuous predicted delta as score, sign(empirical) > 0 as label
    try:
        from sklearn.metrics import roc_auc_score, average_precision_score
        # Exclude zero-empirical entries
        nonzero = emp_sign != 0
        if nonzero.sum() > 10:
            auroc = float(roc_auc_score(emp_pos[nonzero].astype(int), all_pred[nonzero]))
            auprc = float(average_precision_score(emp_pos[nonzero].astype(int), all_pred[nonzero]))
        else:
            auroc = auprc = np.nan
    except Exception:
        auroc = auprc = np.nan

    overall_r = _pearsonr_safe(all_gt, all_pred)
    overall_rho = _spearmanr_safe(all_gt, all_pred)
    ss_res = np.sum((all_pred - all_gt) ** 2)
    ss_tot = np.sum((all_gt - all_gt.mean()) ** 2)
    overall_r2 = float(1 - ss_res / ss_tot) if ss_tot > 0 else np.nan

    results["overall"] = {
        "pearson_r": overall_r,
        "spearman_rho": overall_rho,
        "r_squared": overall_r2,
        "sign_accuracy": sign_acc,
        "sensitivity_positive": sensitivity,
        "specificity_negative": specificity,
        "balanced_accuracy": balanced_acc,
        "mcc": mcc,
        "auroc": auroc,
        "auprc_positive_class": auprc,
        "precision_positive": precision,
        "confusion": {"tp": tp, "fp": fp, "fn": fn, "tn": tn},
        "n_total": n_total,
        "n_zero_empirical": n_zero,
        "frac_positive": float(emp_pos.sum() / n_total) if n_total > 0 else np.nan,
        "positive_class_definition": "empirical_delta > 0 (gene cell-enriched)",
    }
    results["per_ct_pearson"] = {k: v for k, v in per_ct_corr.items() if not np.isnan(v)}
    results["per_ct_r2"] = {k: v for k, v in per_ct_r2.items() if not np.isnan(v)}
    results["median_ct_pearson"] = float(np.nanmedian(list(per_ct_corr.values())))

    # Neuronal vs non-neuronal
    for group_name, prefixes in [("neuronal", NEURON_CT_PREFIXES), ("non_neuronal", GLIA_CT_PREFIXES)]:
        group_cts = [ct for ct in common_cts if any(p in ct for p in prefixes)]
        group_gt, group_pred = [], []
        for ct in group_cts:
            if ct in val_cell_means and ct in val_nuc_means and ct in imp_means:
                group_gt.append(val_cell_means[ct] - val_nuc_means[ct])
                group_pred.append(imp_means[ct] - val_nuc_means[ct])
        if group_gt:
            gt_cat = np.concatenate(group_gt)
            pred_cat = np.concatenate(group_pred)
            results[f"delta_{group_name}"] = {
                "pearson_r": _pearsonr_safe(gt_cat, pred_cat),
                "sign_accuracy": float((np.sign(gt_cat) == np.sign(pred_cat)).mean()),
                "n_cts": len(group_cts),
            }

    # Gene class stratification
    gene_list = list(gene_names)
    for class_name, gene_set, expected_sign in [
        ("ribosomal", RIBOSOMAL_GENES, +1),
        ("nuclear_lncrna", NUCLEAR_LNCRNA_GENES, -1),
        ("cytoplasmic", CYTOPLASMIC_GENES, +1),
    ]:
        idx = [gene_list.index(g) for g in gene_set if g in gene_list]
        if not idx:
            continue
        class_gt = all_gt.reshape(-1, len(gene_list))[:, idx].ravel()
        class_pred = all_pred.reshape(-1, len(gene_list))[:, idx].ravel()
        results[f"delta_{class_name}"] = {
            "pearson_r": _pearsonr_safe(class_gt, class_pred),
            "sign_accuracy": float((np.sign(class_gt) == np.sign(class_pred)).mean()),
            "n_genes_found": len(idx),
            "mean_empirical_delta": float(class_gt.mean()),
            "mean_predicted_delta": float(class_pred.mean()),
        }

    return results


def compartment_scores(imputed, X_nuc, gene_names):
    """Score delta direction for known compartment gene sets."""
    delta = imputed.mean(axis=0) - X_nuc.mean(axis=0)
    gene_list = list(gene_names)

    def _score_set(gene_set, expected_sign):
        idx = [gene_list.index(g) for g in gene_set if g in gene_list]
        if not idx:
            return {"n_found": 0}
        deltas = delta[idx]
        if expected_sign > 0:
            frac_correct = float((deltas > 0).mean())
        else:
            frac_correct = float((deltas < 0).mean())
        return {
            "n_found": len(idx),
            "mean_delta": float(deltas.mean()),
            "median_delta": float(np.median(deltas)),
            "frac_correct_sign": frac_correct,
        }

    return {
        "ribosomal": _score_set(RIBOSOMAL_GENES, +1),
        "cytoplasmic": _score_set(CYTOPLASMIC_GENES, +1),
        "nuclear_lncrna": _score_set(NUCLEAR_LNCRNA_GENES, -1),
    }


def ct_specific_delta(imputed, X_nuc, ct_nuc, gene_names, common_cts):
    """Test whether neuronal marker genes have larger delta in neurons vs glia."""
    gene_list = list(gene_names)
    neuron_idx = [gene_list.index(g) for g in NEURONAL_MARKER_GENES if g in gene_list]
    if not neuron_idx:
        return {"n_genes_found": 0}

    neuron_cts = [ct for ct in common_cts if any(x in ct for x in NEURON_CT_PREFIXES)]
    glia_cts = [ct for ct in common_cts if any(x in ct for x in GLIA_CT_PREFIXES)]

    def _mean_delta(ct_list):
        deltas = []
        for ct in ct_list:
            mask = ct_nuc == ct
            if mask.sum() < 5:
                continue
            d = imputed[mask][:, neuron_idx].mean() - X_nuc[mask][:, neuron_idx].mean()
            deltas.append(d)
        return deltas

    neuron_d = _mean_delta(neuron_cts)
    glia_d = _mean_delta(glia_cts)

    return {
        "n_genes_found": len(neuron_idx),
        "mean_delta_neurons": float(np.mean(neuron_d)) if neuron_d else None,
        "mean_delta_glia": float(np.mean(glia_d)) if glia_d else None,
        "neuron_gt_glia": bool(neuron_d and glia_d and np.mean(neuron_d) > np.mean(glia_d)),
        "ratio": float(np.mean(neuron_d) / np.mean(glia_d))
            if neuron_d and glia_d and np.mean(glia_d) != 0 else None,
    }


