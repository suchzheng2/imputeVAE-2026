def load_manifest():
    """Load split manifest and return as DataFrame."""
    df = pd.read_csv(MANIFEST_PATH, sep="\t", dtype=str)
    assert set(df["partition"].unique()) == {"train", "valid", "test"}, \
        f"Unexpected partitions: {df['partition'].unique()}"
    return df


def load_adata_partitioned(data_dir, batch_suffix, gene_list_path=DEFAULT_GENE_LIST):
    """Load raw h5ad, filter, normalize to log1p, return full adata with obs_id index."""
    path = os.path.join(DATA_ROOT, data_dir, "data.h5ad")
    adata = ad.read_h5ad(path)

    if "meta_batch_id" not in adata.obs:
        adata.obs["meta_batch_id"] = adata.obs["batch_id"].apply(lambda x: x.split(".")[0])

    # Protocol filter
    adata = adata[adata.obs["meta_batch_id"].str.endswith(batch_suffix)].copy()

    # Common genes + cell types + gene list
    common_genes = pd.read_csv(os.path.join(PROJECT_ROOT, "data", "common_genes.csv"),
                               header=0)["common_genes"].tolist()
    common_ct = pd.read_csv(os.path.join(PROJECT_ROOT, "data", "common_cell_types.csv"),
                            header=0)["common_cell_types"].tolist()
    gene_list = pd.read_csv(gene_list_path, header=None)[0].tolist()

    adata = adata[adata.obs["cell_type"].isin(common_ct)].copy()
    col_mask = adata.var["gene_names"].isin(common_genes) & adata.var["gene_names"].isin(gene_list)
    adata = adata[:, col_mask].copy()
    adata = adata[:, adata.var["gene_names"].argsort()].copy()

    # log1p normalize
    X = adata.X.toarray() if sparse.issparse(adata.X) else adata.X
    adata.X = np.log1p(X).astype(np.float32)

    return adata


def subset_by_partition(adata, manifest_df, modality, partition):
    """Subset adata to rows matching the given partition.

    Returns a new adata with only the requested partition's observations.
    """
    mask_df = manifest_df[
        (manifest_df["modality"] == modality) & (manifest_df["partition"] == partition)
    ]
    valid_obs_ids = set(mask_df["obs_id"].values)
    obs_ids = adata.obs.index.astype(str)
    mask = obs_ids.isin(valid_obs_ids)
    result = adata[mask].copy()
    return result


