def permutation_test_delta(imp_means, val_cell_means, val_nuc_means, common_cts,
                           n_permutations=1000):
    """Scrambled-label null for delta correlation.

    Permutes cell-type labels on validation cell data, recomputes empirical delta,
    then measures correlation with predicted delta. Reports empirical p-value.
    """
    # Observed
    cts_used = [ct for ct in common_cts
                if ct in imp_means and ct in val_cell_means and ct in val_nuc_means]
    all_gt = np.concatenate([val_cell_means[ct] - val_nuc_means[ct] for ct in cts_used])
    all_pred = np.concatenate([imp_means[ct] - val_nuc_means[ct] for ct in cts_used])
    observed_r = _pearsonr_safe(all_gt, all_pred)

    # Permutations: shuffle which CT means are paired
    rng = np.random.RandomState(42)
    n_extreme = 0
    perm_rs = []
    for _ in range(n_permutations):
        shuffled_cts = list(cts_used)
        rng.shuffle(shuffled_cts)
        perm_gt = np.concatenate([val_cell_means[ct] - val_nuc_means[ct] for ct in shuffled_cts])
        perm_r = _pearsonr_safe(perm_gt, all_pred)
        perm_rs.append(perm_r)
        if abs(perm_r) >= abs(observed_r):
            n_extreme += 1

    p_value = (n_extreme + 1) / (n_permutations + 1)

    return {
        "observed_r": observed_r,
        "n_permutations": n_permutations,
        "n_extreme": n_extreme,
        "p_value": float(p_value),
        "p_label": f"p < {1/(n_permutations+1):.3f}" if n_extreme == 0 else f"p = {p_value:.4f}",
        "perm_r_mean": float(np.mean(perm_rs)),
        "perm_r_std": float(np.std(perm_rs)),
        "z_score": float((observed_r - np.mean(perm_rs)) / np.std(perm_rs)) if np.std(perm_rs) > 0 else np.nan,
    }


