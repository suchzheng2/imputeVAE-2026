def evaluate_method(name, imputed, ct_imp,
                    X_val_cell, ct_val_cell,
                    X_val_nuc, ct_val_nuc,
                    val_cell_means, val_nuc_means,
                    X_train_cell, ct_train_cell,
                    gene_names, common_cts):
    """Run all metrics for one method. Returns results dict."""
    print(f"\n{'='*60}")
    print(f"Evaluating: {name}")
    print(f"  imputed: {imputed.shape}, val_cell: {X_val_cell.shape}, val_nuc: {X_val_nuc.shape}")
    print(f"  common CTs: {len(common_cts)}")
    print(f"{'='*60}")

    results = {"method": name}
    imp_means = compute_ct_means(imputed, ct_imp, common_cts)

    # --- CT-level metrics ---
    print("  Gene correlation...")
    gc_per_gene, gc_summary = gene_correlation(imp_means, val_cell_means, common_cts)
    results["gene_corr"] = gc_summary
    # Also compute raw nucleus gene corr for reference
    nuc_means_for_gc = compute_ct_means(X_val_nuc, ct_val_nuc, common_cts)
    _, gc_nuc = gene_correlation(nuc_means_for_gc, val_cell_means, common_cts)
    results["gene_corr_raw_nuc"] = gc_nuc

    print("  R-squared...")
    results["r_squared"] = r_squared_ct(imp_means, val_cell_means, common_cts)

    print("  Shift scores...")
    shift_per_ct, shift_summary = shift_scores(imp_means, val_cell_means, val_nuc_means, common_cts)
    results["shift"] = shift_summary
    results["shift_per_ct"] = shift_per_ct

    print("  Classification (train cells -> imputed)...")
    results["clf_imputed"] = classification_accuracy(
        X_train_cell, ct_train_cell, imputed, ct_imp, common_cts
    )
    results["clf_raw_nuc"] = classification_accuracy(
        X_train_cell, ct_train_cell, X_val_nuc, ct_val_nuc, common_cts
    )

    # --- Sample-level metrics ---
    print("  Variance retention...")
    vr_per_ct, vr_summary = variance_retention(imputed, ct_imp, X_val_cell, ct_val_cell, common_cts)
    results["variance_retention"] = vr_summary
    results["variance_retention_per_ct"] = vr_per_ct

    # Sanity check for CT-mean baseline
    if name == "ctmean":
        for ct, ratio in vr_per_ct.items():
            if not np.isnan(ratio):
                assert abs(ratio) < 1e-8, \
                    f"CT-mean baseline has nonzero variance for {ct}: {ratio}"
        print("  CT-mean variance = 0 assertion PASSED")

    print("  Per-profile centroid correlation...")
    ppc_per_ct, ppc_summary = per_profile_centroid_corr(imputed, ct_imp, val_cell_means, common_cts)
    results["per_profile_centroid_corr"] = ppc_summary
    results["per_profile_centroid_corr_per_ct"] = ppc_per_ct

    print("  Within-CT Spearman...")
    if imputed.shape[0] == X_val_nuc.shape[0]:
        sp_per_ct, sp_summary = within_ct_spearman(imputed, ct_imp, X_val_nuc, ct_val_nuc, common_cts)
        results["within_ct_spearman"] = sp_summary
    else:
        results["within_ct_spearman"] = {"overall_median": None, "note": "size_mismatch"}

    # --- Label-free metrics ---
    print("  QQ gene correlation (label-free)...")
    results["qq_gene_corr"] = qq_gene_correlation(imputed, X_val_cell)

    print("  Wasserstein distance (label-free)...")
    results["wasserstein"] = wasserstein_per_gene(imputed, X_val_cell)

    # --- Biological validation ---
    print("  Delta analysis...")
    results["delta"] = delta_analysis(imp_means, val_cell_means, val_nuc_means, common_cts, gene_names)

    print("  Compartment scores...")
    results["compartment"] = compartment_scores(imputed, X_val_nuc, gene_names)

    print("  CT-specific delta...")
    results["ct_specific"] = ct_specific_delta(imputed, X_val_nuc, ct_val_nuc, gene_names, common_cts)

    # --- Permutation test ---
    print("  Permutation test (1000 permutations)...")
    results["permutation"] = permutation_test_delta(imp_means, val_cell_means, val_nuc_means, common_cts)

    return results


