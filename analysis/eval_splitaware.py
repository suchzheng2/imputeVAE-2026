def sensitivity_analysis(results_full, imputed, ct_imp, X_val_cell, ct_val_cell,
                         X_val_nuc, ct_val_nuc, val_cell_means, val_nuc_means,
                         gene_names, common_cts, manifest_df, method_name):
    """Repeat aggregate metrics excluding rare cell types."""
    sensitivity = {}
    for min_n in [10, 20]:
        # Find CTs with enough validation samples in BOTH modalities
        cts_ok = []
        for ct in common_cts:
            n_cell = (ct_val_cell == ct).sum()
            n_nuc = (ct_val_nuc == ct).sum()
            if n_cell >= min_n and n_nuc >= min_n:
                cts_ok.append(ct)
            else:
                pass  # excluded

        imp_means = compute_ct_means(imputed, ct_imp, cts_ok)
        vcm = {ct: val_cell_means[ct] for ct in cts_ok if ct in val_cell_means}
        vnm = {ct: val_nuc_means[ct] for ct in cts_ok if ct in val_nuc_means}

        _, gc = gene_correlation(imp_means, vcm, cts_ok)
        _, sh = shift_scores(imp_means, vcm, vnm, cts_ok)
        vr_per_ct, vr = variance_retention(imputed, ct_imp, X_val_cell, ct_val_cell, cts_ok)

        sensitivity[f"min_{min_n}"] = {
            "n_cts": len(cts_ok),
            "excluded_cts": [ct for ct in common_cts if ct not in cts_ok],
            "gene_corr_median": gc["median"],
            "shift_mean": sh["mean_shift"],
            "variance_median": vr["median_ratio"],
        }

    return sensitivity


