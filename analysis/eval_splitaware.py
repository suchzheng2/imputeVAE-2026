def compute_ct_means(X, ct_labels, common_cts):
    """Compute per-cell-type mean expression. Returns dict[ct] -> 1D array."""
    means = {}
    for ct in common_cts:
        mask = ct_labels == ct
        if mask.sum() > 0:
            means[ct] = X[mask].mean(axis=0)
    return means


def _pearsonr_safe(a, b):
    """Pearson correlation, returns NaN if either has zero variance."""
    if np.std(a) == 0 or np.std(b) == 0:
        return np.nan
    r, _ = stats.pearsonr(a, b)
    return float(r)


def _spearmanr_safe(a, b):
    if np.std(a) == 0 or np.std(b) == 0:
        return np.nan
    r, _ = stats.spearmanr(a, b)
    return float(r)


def gene_correlation(imp_means, target_means, common_cts):
    """Per-gene Pearson correlation across cell types.

    For each gene g, correlates imp_means[:, g] vs target_means[:, g]
    across the ~17 common cell types.

    Returns per-gene array and summary dict.
    """
    imp_matrix = np.array([imp_means[ct] for ct in common_cts if ct in imp_means and ct in target_means])
    tgt_matrix = np.array([target_means[ct] for ct in common_cts if ct in imp_means and ct in target_means])
    n_genes = imp_matrix.shape[1]
    corrs = np.full(n_genes, np.nan)
    for g in range(n_genes):
        corrs[g] = _pearsonr_safe(imp_matrix[:, g], tgt_matrix[:, g])
    valid = ~np.isnan(corrs)
    return corrs, {
        "median": float(np.nanmedian(corrs)),
        "mean": float(np.nanmean(corrs)),
        "q25": float(np.nanpercentile(corrs, 25)),
        "q75": float(np.nanpercentile(corrs, 75)),
        "n_valid": int(valid.sum()),
        "n_total": n_genes,
    }


def r_squared_ct(imp_means, target_means, common_cts):
    """Per-gene R² across cell types."""
    imp_matrix = np.array([imp_means[ct] for ct in common_cts if ct in imp_means and ct in target_means])
    tgt_matrix = np.array([target_means[ct] for ct in common_cts if ct in imp_means and ct in target_means])
    n_genes = imp_matrix.shape[1]
    r2 = np.full(n_genes, np.nan)
    for g in range(n_genes):
        ss_res = np.sum((imp_matrix[:, g] - tgt_matrix[:, g]) ** 2)
        ss_tot = np.sum((tgt_matrix[:, g] - tgt_matrix[:, g].mean()) ** 2)
        r2[g] = float(1 - ss_res / ss_tot) if ss_tot > 0 else np.nan
    return {
        "median": float(np.nanmedian(r2)),
        "mean": float(np.nanmean(r2)),
        "q25": float(np.nanpercentile(r2, 25)),
        "q75": float(np.nanpercentile(r2, 75)),
    }


def shift_scores(imp_means, cell_means, nuc_means, common_cts):
    """Shift score: corr(imputed, cell) - corr(imputed, nuclei) per cell type.

    Positive shift means imputed is closer to cell than to nucleus.
    """
    per_ct = {}
    for ct in common_cts:
        if ct not in imp_means or ct not in cell_means or ct not in nuc_means:
            continue
        corr_cell = _pearsonr_safe(imp_means[ct], cell_means[ct])
        corr_nuc = _pearsonr_safe(imp_means[ct], nuc_means[ct])
        if not np.isnan(corr_cell) and not np.isnan(corr_nuc):
            per_ct[ct] = corr_cell - corr_nuc
    shifts = list(per_ct.values())
    return per_ct, {
        "mean_shift": float(np.mean(shifts)) if shifts else np.nan,
        "median_shift": float(np.median(shifts)) if shifts else np.nan,
    }


def variance_retention(imputed, ct_imp, X_cell, ct_cell, common_cts):
    """Within-CT variance ratio: var(imputed) / var(real_cell), per cell type.

    For each CT, computes mean across genes of per-gene variance.
    Ratio < 1 means variance collapse. Ratio = 0 for CT-mean baseline.
    """
    per_ct = {}
    for ct in common_cts:
        imp_mask = ct_imp == ct
        cell_mask = ct_cell == ct
        if imp_mask.sum() < 5 or cell_mask.sum() < 5:
            per_ct[ct] = np.nan
            continue
        imp_var = imputed[imp_mask].var(axis=0).mean()
        cell_var = X_cell[cell_mask].var(axis=0).mean()
        per_ct[ct] = float(imp_var / cell_var) if cell_var > 0 else np.nan

    ratios = [v for v in per_ct.values() if not np.isnan(v)]
    # Sample-size weighted aggregate
    weighted_num, weighted_den = 0.0, 0.0
    for ct in common_cts:
        if ct not in per_ct or np.isnan(per_ct[ct]):
            continue
        n = (ct_imp == ct).sum()
        weighted_num += per_ct[ct] * n
        weighted_den += n
    weighted = weighted_num / weighted_den if weighted_den > 0 else np.nan

    return per_ct, {
        "median_ratio": float(np.median(ratios)) if ratios else np.nan,
        "mean_ratio": float(np.mean(ratios)) if ratios else np.nan,
        "q25": float(np.percentile(ratios, 25)) if ratios else np.nan,
        "q75": float(np.percentile(ratios, 75)) if ratios else np.nan,
        "weighted_ratio": float(weighted),
    }


def per_profile_centroid_corr(imputed, ct_imp, cell_means, common_cts):
    """Per-profile centroid correlation: each imputed profile vs its CT centroid.

    Renamed from per_cell_corr to clarify this is NOT correlation with a paired cell.
    The centroid is the validation cell mean for that cell type.
    """
    per_ct = {}
    all_corrs = []
    for ct in common_cts:
        if ct not in cell_means:
            continue
        mask = ct_imp == ct
        centroid = cell_means[ct]
        ct_corrs = []
        for i in np.where(mask)[0]:
            r = _pearsonr_safe(imputed[i], centroid)
            if not np.isnan(r):
                ct_corrs.append(r)
        if ct_corrs:
            per_ct[ct] = float(np.median(ct_corrs))
            all_corrs.extend(ct_corrs)

    return per_ct, {
        "overall_median": float(np.median(all_corrs)) if all_corrs else np.nan,
        "overall_mean": float(np.mean(all_corrs)) if all_corrs else np.nan,
        "q25": float(np.percentile(all_corrs, 25)) if all_corrs else np.nan,
        "q75": float(np.percentile(all_corrs, 75)) if all_corrs else np.nan,
    }


def within_ct_spearman(imputed, ct_imp, X_nuc, ct_nuc, common_cts, n_genes_sample=1000):
    """Per-gene Spearman rank preservation within cell type."""
    n_genes = imputed.shape[1]
    rng = np.random.RandomState(42)
    gene_idx = rng.choice(n_genes, min(n_genes_sample, n_genes), replace=False)

    per_ct = {}
    all_corrs = []
    for ct in common_cts:
        imp_mask = ct_imp == ct
        nuc_mask = ct_nuc == ct
        if imp_mask.sum() < 5:
            continue
        ct_corrs = []
        for g in gene_idx:
            imp_vals = imputed[imp_mask, g]
            nuc_vals = X_nuc[nuc_mask, g]
            if len(imp_vals) != len(nuc_vals):
                continue
            r = _spearmanr_safe(imp_vals, nuc_vals)
            if not np.isnan(r):
                ct_corrs.append(r)
        if ct_corrs:
            per_ct[ct] = float(np.median(ct_corrs))
            all_corrs.extend(ct_corrs)

    return per_ct, {
        "overall_median": float(np.median(all_corrs)) if all_corrs else np.nan,
        "overall_mean": float(np.mean(all_corrs)) if all_corrs else np.nan,
    }


def qq_gene_correlation(imputed, X_cell, n_quantiles=500):
    """Per-gene QQ correlation (label-free)."""
    n_genes = imputed.shape[1]
    quantiles = np.linspace(0, 1, n_quantiles)
    imp_q = np.quantile(imputed, quantiles, axis=0)
    cell_q = np.quantile(X_cell, quantiles, axis=0)
    corrs = np.zeros(n_genes)
    for g in range(n_genes):
        corrs[g] = _pearsonr_safe(imp_q[:, g], cell_q[:, g])
    return {
        "median": float(np.nanmedian(corrs)),
        "mean": float(np.nanmean(corrs)),
    }


def wasserstein_per_gene(imputed, X_cell, n_genes_sample=200):
    """Per-gene Wasserstein-1 distance."""
    n_genes = imputed.shape[1]
    gene_var = X_cell.var(axis=0)
    gene_idx = np.argsort(gene_var)[-min(n_genes_sample, n_genes):]
    n_common = min(imputed.shape[0], X_cell.shape[0], 5000)
    quantiles = np.linspace(0, 1, n_common)
    dists = []
    for g in gene_idx:
        imp_q = np.quantile(imputed[:, g], quantiles)
        cell_q = np.quantile(X_cell[:, g], quantiles)
        dists.append(np.mean(np.abs(imp_q - cell_q)))
    return {
        "median": float(np.median(dists)),
        "mean": float(np.mean(dists)),
        "n_genes": len(dists),
    }


