def generate_cvae_predictions(run_dir, X_val_nuc, batch_size=512):
    """Cross-decode validation nuclei through the trained cVAE."""
    import torch
    from imputeVAE.models_cond import VAE_JSD_Cond

    with open(os.path.join(run_dir, "arguments.json")) as f:
        config = json.load(f)

    num_internal = config["num_internal"]
    if isinstance(num_internal, str):
        num_internal = [int(x) for x in num_internal.split(",")]

    model = VAE_JSD_Cond(
        input_size=config["num_feature"],
        num_internal=num_internal,
        num_latent=config["num_latent"],
        embed_dim=config.get("embed_dim", 8),
        scalar_cond=config.get("scalar_cond", False),
        cond_encoder=config.get("cond_encoder", False),
    )
    model_path = os.path.join(run_dir, "models", "model.pt")
    model.load_state_dict(torch.load(model_path, map_location="cpu"))
    model.eval()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = model.to(device)
    print(f"  cVAE model loaded from {model_path} -> {device}")

    n = X_val_nuc.shape[0]
    imputed = np.zeros_like(X_val_nuc)
    with torch.no_grad():
        for start in range(0, n, batch_size):
            end = min(start + batch_size, n)
            batch = torch.from_numpy(X_val_nuc[start:end]).to(device)
            decoded = model.decode_cross(batch, source_modality_id=1, target_modality_id=0)
            imputed[start:end] = decoded.cpu().numpy()
    return imputed.astype(np.float32)


def generate_ctmean_predictions(train_cell_means, ct_val_nuc, n_genes):
    """CT-mean baseline: assign each validation nucleus its training cell-type mean."""
    n = len(ct_val_nuc)
    imputed = np.zeros((n, n_genes), dtype=np.float32)
    for i, ct in enumerate(ct_val_nuc):
        if ct in train_cell_means:
            imputed[i] = train_cell_means[ct]
    return imputed


def generate_linreg_predictions(train_cell_means, train_nuc_means, X_val_nuc, ct_val_nuc,
                                common_cts):
    """Per-gene linear regression: fitted on training CT means, applied to validation nuclei."""
    n_genes = X_val_nuc.shape[1]
    # Build training matrices from CT means
    cts_for_fit = [ct for ct in common_cts if ct in train_cell_means and ct in train_nuc_means]
    cell_matrix = np.array([train_cell_means[ct] for ct in cts_for_fit])
    nuc_matrix = np.array([train_nuc_means[ct] for ct in cts_for_fit])

    imputed = np.zeros_like(X_val_nuc)
    for g in range(n_genes):
        reg = LinearRegression()
        reg.fit(nuc_matrix[:, g:g+1], cell_matrix[:, g])
        imputed[:, g] = reg.predict(X_val_nuc[:, g:g+1])

    return imputed.astype(np.float32)


