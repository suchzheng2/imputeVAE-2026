def classification_accuracy(X_train_cell, ct_train_cell, imputed, ct_imp, common_cts,
                            max_per_ct=2000):
    """Train classifier on training cells, predict on imputed validation nuclei."""
    from sklearn.linear_model import LogisticRegression
    from sklearn.preprocessing import StandardScaler
    from sklearn.metrics import accuracy_score, f1_score

    # Subsample training cells
    rng = np.random.RandomState(42)
    idx = []
    for ct in common_cts:
        ct_idx = np.where(ct_train_cell == ct)[0]
        if len(ct_idx) > max_per_ct:
            ct_idx = rng.choice(ct_idx, max_per_ct, replace=False)
        idx.extend(ct_idx)
    X_train = X_train_cell[sorted(idx)]
    y_train = ct_train_cell[sorted(idx)]

    # Only keep common CTs in imputed
    imp_mask = np.isin(ct_imp, common_cts)
    X_test = imputed[imp_mask]
    y_test = ct_imp[imp_mask]

    scaler = StandardScaler()
    X_train_s = scaler.fit_transform(X_train)
    X_test_s = scaler.transform(X_test)

    clf = LogisticRegression(max_iter=1000, random_state=42, n_jobs=-1)
    clf.fit(X_train_s, y_train)
    y_pred = clf.predict(X_test_s)

    return {
        "accuracy": float(accuracy_score(y_test, y_pred)),
        "macro_f1": float(f1_score(y_test, y_pred, average="macro", zero_division=0)),
    }


